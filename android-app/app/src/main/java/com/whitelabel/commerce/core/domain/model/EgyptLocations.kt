    fun findGovernorate(raw: String?): EgyptGovernorate? {
        val clean = raw?.trim()?.lowercase().orEmpty()
        if (clean.isEmpty()) return null
        return governorates.firstOrNull { g ->
            g.id == clean || g.nameAr.lowercase() == clean || g.nameEn.lowercase() == clean
        }
    }

    fun findCity(governorate: EgyptGovernorate?, rawCity: String?): EgyptCity? {
        val clean = rawCity?.trim()?.lowercase().orEmpty()
        if (governorate == null || clean.isEmpty()) return null
        return governorate.cities.firstOrNull { c ->
            c.nameAr.lowercase() == clean || c.nameEn.lowercase() == clean
        }
    }
