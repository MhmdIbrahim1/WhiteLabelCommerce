export type Lang = "ar" | "en";

export const LANG_COOKIE = "nova_lang";
export const LANG_STORAGE_KEY = "nova.lang";

export function isLang(value: unknown): value is Lang {
  return value === "ar" || value === "en";
}

export function langDir(lang: Lang): "rtl" | "ltr" {
  return lang === "en" ? "ltr" : "rtl";
}

export function langHtmlAttr(lang: Lang): string {
  return lang === "en" ? "en" : "ar-EG";
}

export function localizedText(
  lang: Lang,
  ar: string | null | undefined,
  en?: string | null | undefined,
): string {
  if (lang === "en" && en && en.trim()) return en.trim();
  return ar ?? "";
}

export function formatMoney(
  value: number | null,
  currency = "EGP",
  lang: Lang = "ar",
): string {
  if (value === null) {
    return lang === "en" ? "Awaiting pricing" : "بانتظار التسعير";
  }
  const locale = lang === "en" ? "en-US" : "ar-EG";
  return new Intl.NumberFormat(locale, {
    style: "currency",
    currency,
  }).format(value);
}

export function formatDate(value: string, lang: Lang = "ar"): string {
  const locale = lang === "en" ? "en-GB" : "ar-EG";
  return new Intl.DateTimeFormat(locale, {
    dateStyle: "medium",
    timeZone: "Africa/Cairo",
  }).format(new Date(value));
}

