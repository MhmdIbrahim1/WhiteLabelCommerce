const EN_COLOR_MAP: Record<string, string> = Object.fromEntries(
  Object.entries(AR_COLOR_MAP).map(([ar, en]) => [en.toLowerCase(), ar]),
);

export function translateColor(value: string, lang: Lang): string {
  const clean = value.trim();
  if (!clean) return clean;
  const parts = clean.split("/").map((p) => p.trim());
  const mapped = parts.map((part) => {
    if (lang === "en") {
      return AR_COLOR_MAP[part] ?? part;
    }
    return EN_COLOR_MAP[part.toLowerCase()] ?? part;
  });
  return mapped.join(" / ");
}

