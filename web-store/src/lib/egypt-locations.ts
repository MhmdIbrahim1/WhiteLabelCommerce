export function findEgyptGovernorate(raw: string | null | undefined): EgyptGovernorate | undefined {
  const clean = (raw ?? "").trim().toLowerCase();
  if (!clean) return undefined;
  return EGYPT_GOVERNORATES.find(
    (g) =>
      g.id === clean ||
      g.name_ar.toLowerCase() === clean ||
      g.name_en.toLowerCase() === clean,
  );
}

export function findEgyptCity(
  gov: EgyptGovernorate | undefined,
  rawCity: string | null | undefined,
): EgyptCity | undefined {
  const clean = (rawCity ?? "").trim().toLowerCase();
  if (!gov || !clean) return undefined;
  return gov.cities.find(
    (c) =>
      c.name_ar.toLowerCase() === clean || c.name_en.toLowerCase() === clean,
  );
}

export function composeEgyptShippingAddress(
  governorate: string,
  city: string,
  street: string,
): string {
  const g = governorate.trim();
  const c = city.trim();
  const s = street.trim();
  const parts: string[] = [];
  if (g && !s.toLowerCase().includes(g.toLowerCase())) parts.push(g);
  if (c && !s.toLowerCase().includes(c.toLowerCase())) parts.push(c);
  if (s) parts.push(s);
  return parts.join(" - ");
}
